"""Copy the CV PDFs into assets/cv/cv-data.js as base64.

The resume window reads the PDF files directly when it can (GitHub Pages, Live Server).
Some places block that (opening index.html by double-click, some previews), so the
viewer falls back to this embedded copy. Run this after replacing a CV:

    python3 scripts/embed-cv.py
"""
import base64
import json
from pathlib import Path

project_folder = Path(__file__).resolve().parent.parent
cv_folder = project_folder / "assets" / "cv"
cv_files = {
    "en": "Anas_Alnagar_Frontend_Developer_CV_EN.pdf",
    "es": "Anas_Alnagar_Desarrollador_Frontend_CV_ES.pdf",
}

embedded_data = {
    language: base64.b64encode((cv_folder / file_name).read_bytes()).decode("ascii")
    for language, file_name in cv_files.items()
}
output_path = cv_folder / "cv-data.js"
output_path.write_text(
    "// Generated by scripts/embed-cv.py. Do not edit by hand.\n"
    f"window.resumePdfData = {json.dumps(embedded_data, indent=2)};\n"
)
print(f"Wrote {output_path.relative_to(project_folder)} ({output_path.stat().st_size // 1024} KB)")
